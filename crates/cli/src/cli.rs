#[derive(Parser, Debug)]
#[command(
    name = "xssh",
    version,
    about = "SSH client for AI agents: managed hosts & secrets, persistent sessions, prompt automation, structured output.",
    after_help = "Global options (any position): --json (structured output), --no-daemon (in-process; no sessions/forwards), --home DIR (data dir; default `data` beside the exe); env XSSH_JSON, XSSH_NO_DAEMON, XSSH_HOME.\nRun `xssh guide` for the agent manual."
)]
pub struct Cli {
    /// Print structured JSON instead of compact text.
    #[arg(long, global = true, hide = true, env = "XSSH_JSON")]
    pub json: bool,
    /// Run in-process without the background daemon (no sessions/forwards).
    #[arg(long, global = true, hide = true, env = "XSSH_NO_DAEMON")]
    pub no_daemon: bool,
    /// xssh home directory (config, hosts, logs) [default: `data` next to the xssh executable].
    #[arg(long, global = true, hide = true, env = "XSSH_HOME")]
    pub home: Option<PathBuf>,
    #[command(subcommand)]
    pub cmd: Cmd,
}


/// Screen conditions for `session send/read/wait`.
#[derive(Args, Debug, Default)]
pub struct WaitArgs {
    /// Return as soon as this regex is on screen (or in new output).
    #[arg(long, allow_hyphen_values = true)]
    until: Option<String>,
    /// Return once this regex is no longer on screen.
    #[arg(long, allow_hyphen_values = true)]
    gone: Option<String>,
    /// Return once the screen is unchanged for this long (spinners/counters ignored) and no busy
    /// marker such as "esc to interrupt" is visible.
    #[arg(long)]
    stable: Option<String>,
}

impl WaitArgs {
    fn spec(self, default_stable: bool) -> Result<xssh_engine::session::WaitSpec> {
        if let Some(r) = self.until.as_deref().or(self.gone.as_deref()) {
            regex::Regex::new(r)?;
        }
        let stable_ms = self.stable.as_deref().map(dur_ms).transpose()?;
        // `session wait` with no condition: the running command's end (a full-screen program:
        // a stable screen).
        let run_end = default_stable && self.until.is_none() && self.gone.is_none() && stable_ms.is_none();
        Ok(xssh_engine::session::WaitSpec {
            until: self.until,
            gone: self.gone,
            stable_ms,
            run_end,
        })
    }
}


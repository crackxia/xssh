/// The reader identity for session requests (see [`SessionArgs::agent`]).
fn session_agent(explicit: Option<String>) -> Option<String> {
    explicit.filter(|a| !a.trim().is_empty()).or_else(|| {
        std::env::var("CLAUDE_CODE_SESSION_ID")
            .ok()
            .filter(|v| !v.is_empty())
            .map(|v| format!("claude-{}", v.chars().take(8).collect::<String>()))
    })
}

